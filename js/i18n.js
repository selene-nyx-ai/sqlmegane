function getLocale() { return locale; }
function setLocale(next) {
  const normalized = String(next || '').toLowerCase();
  if (!locales.includes(normalized)) return false;
  locale = normalized;
  return true;
}
function t(key, params) {
  let value = messages[locale][key];
  if (value === undefined) {
    value = messages.ja[key];
    if (!warned.has(key)) {
      warned.add(key);
      if (globalThis.console && typeof globalThis.console.warn === 'function') console.warn(`[SQLMegane i18n] Missing ${locale} message: ${key}`);
    }
  }
  if (value === undefined) {
    if (!warned.has(key)) {
      warned.add(key);
      if (globalThis.console && typeof globalThis.console.warn === 'function') console.warn(`[SQLMegane i18n] Unknown message key: ${key}`);
    }
    return key;
  }
  return String(value).replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) => params && params[name] !== undefined ? String(params[name]) : `{${name}}`);
}

